/** 展开为条目对象数组 */
function buildItems() {
  const list = [];
  let i = 0;
  for (const g of GROUPS) {
    for (const it of g.items) {
      i += 1;
      list.push({
        id: `LIB${String(i).padStart(3, '0')}`,
        group_key: g.key,
        group_name: g.name,
        name: it[0],
        unit: it[1],
        price: it[2],
        cost: it[3],
        craft: it[4],
        tags: (it[5] || '').split(/\s+/).filter(Boolean),
        source: 'builtin',
      });
    }
  }
  return list;
}

